import { build } from "vite";
import react from "@vitejs/plugin-react";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { readFile, writeFile, rename } from "node:fs/promises";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
await build({
  configFile: false,
  root,
  plugins: [react()],
  define: { "process.env.NODE_ENV": '"production"' },
  resolve: { alias: [
    { find: "infisson_ui/styles.css", replacement: resolve(root, "packages/infisson_ui/src/styles.css") },
    { find: /^infisson_ui$/, replacement: resolve(root, "packages/infisson_ui/src/index.ts") },
  ] },
  build: {
    outDir: resolve(root, ".standalone-build"),
    emptyOutDir: true,
    cssCodeSplit: false,
    lib: { entry: resolve(root, "src/preview-main.tsx"), name: "InfissonPreview", formats: ["iife"], fileName: () => "preview.js", cssFileName: "preview" },
  },
});
const [js, css] = await Promise.all([
  readFile(resolve(root, ".standalone-build/preview.js"), "utf8"),
  readFile(resolve(root, ".standalone-build/preview.css"), "utf8"),
]);
const html = `<!doctype html>
<html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f1f5f8"><title>infisson_ui · 组件预览</title>
<!-- Generated by pnpm preview:update. React, components and CSS are embedded; file:// is supported. -->
<style>${css.replaceAll("</style", "<\\/style")}</style></head><body><div id="root"></div><noscript>请启用 JavaScript 查看组件交互 / Enable JavaScript to preview components.</noscript><script>${js.replaceAll("</script", "<\\/script")}</script></body></html>`;
const temporary = resolve(root, "index.preview-next.html");
await writeFile(temporary, html, "utf8");
await rename(temporary, resolve(root, "index.html"));
console.log(`Updated index.html: ${Buffer.byteLength(html)} bytes; embedded JS and CSS, no server required.`);
